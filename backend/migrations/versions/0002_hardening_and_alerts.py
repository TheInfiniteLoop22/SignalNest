SCHEMA = """
        -- One row per failed login, keyed by the (lower-cased) email that was tried.
        CREATE TABLE login_failures (
            id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email     text NOT NULL,
            failed_at timestamptz NOT NULL DEFAULT now()
        );
        CREATE INDEX ix_login_failures_email_failed ON login_failures (email, failed_at);

        ALTER TABLE monitors ADD COLUMN webhook_url text;

        -- Transactional outbox: written in the same transaction that opens or resolves the
        -- incident, delivered later by the worker with retries.
        CREATE TABLE alerts (
            id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            monitor_id      uuid NOT NULL REFERENCES monitors (id) ON DELETE CASCADE,
            kind            text NOT NULL,
            payload         jsonb NOT NULL,
            created_at      timestamptz NOT NULL DEFAULT now(),
            status          text NOT NULL DEFAULT 'PENDING',
            attempts        smallint NOT NULL DEFAULT 0,
            next_attempt_at timestamptz NOT NULL DEFAULT now(),
            locked_until    timestamptz,
            last_error      text,
            CONSTRAINT ck_alerts_kind CHECK (kind IN ('OPEN', 'RESOLVE')),
            CONSTRAINT ck_alerts_status CHECK (status IN ('PENDING', 'DELIVERED', 'FAILED'))
        );
        CREATE INDEX ix_alerts_pending ON alerts (next_attempt_at) WHERE status = 'PENDING';
        CREATE INDEX ix_alerts_created ON alerts (created_at);

        -- Lets retention delete old runs without scanning every monitor's history.
        CREATE INDEX ix_check_runs_started_at ON check_runs (started_at);
"""


